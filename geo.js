function bboxFor(city) {
  const dLat = city.radius / 111.0;
  const dLon = city.radius / (111.0 * Math.cos(city.lat * Math.PI / 180));
  return [
    city.lat - dLat,
    city.lon - dLon,
    city.lat + dLat,
    city.lon + dLon
  ].map(v => v.toFixed(5)).join(",");
}

